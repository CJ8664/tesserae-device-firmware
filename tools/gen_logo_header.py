#!/usr/bin/env python3
"""Generate include/tesserae_logo.h from the server's rendered brand mark.

Reads a square PNG of the self-hosted mark (the server repo's
static/brand/firmware/tesserae-splash-<size>.png, rendered from
static/brand/icon.svg by scripts/render_brand.py) and reduces it to three
brand tones, one byte per pixel:

    0 = ink tile, 1 = paper (bottom-left square and the corners outside
    the rounded tile), 2 = red top-right square.

src/splash.c maps those tones to the active panel's palette.

Usage:
    gen_logo_header.py path/to/tesserae-splash-192.png include/tesserae_logo.h
"""
import sys
from pathlib import Path

from PIL import Image

INK = (0x1C, 0x1B, 0x19)
PAPER = (0xFF, 0xFD, 0xF8)
RED = (0xD0, 0x49, 0x3C)
TONES = ((INK, 0), (PAPER, 1), (RED, 2))


def tone(rgba):
    r, g, b, a = rgba
    if a < 128:
        return 1  # outside the rounded tile: the splash background is white
    return min(TONES, key=lambda t: sum((p - q) ** 2 for p, q in zip((r, g, b), t[0])))[1]


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    im = Image.open(src).convert("RGBA")
    w, h = im.size
    data = im.load()
    px = [tone(data[x, y]) for y in range(h) for x in range(w)]
    rows = [",".join(str(v) for v in px[i:i + 32]) + "," for i in range(0, len(px), 32)]
    dst.write_text(
        "/*\n"
        " * tesserae_logo.h: Tesserae self-hosted mark (server repo\n"
        f" * static/brand/firmware/{src.name}), reduced to three brand tones:\n"
        " * 0 = ink tile, 1 = paper, 2 = red. src/splash.c maps them to the panel.\n"
        " * Generated by tools/gen_logo_header.py; do not edit by hand.\n"
        " */\n"
        "#pragma once\n"
        "#include <stdint.h>\n"
        f"#define TESSERAE_LOGO_W {w}\n"
        f"#define TESSERAE_LOGO_H {h}\n"
        f"static const uint8_t tesserae_logo[{w * h}] = {{\n"
        + "\n".join(rows)
        + "\n};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
